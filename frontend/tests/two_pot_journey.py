"""Exercise the two-pot UI against the local Python API; no payment is executed."""
from pathlib import Path
from tempfile import gettempdir
import json
import os

from playwright.sync_api import expect, sync_playwright


with sync_playwright() as playwright:
    browser = playwright.chromium.launch(channel="chrome", headless=True)
    for width, height in [(1440, 900), (390, 844), (320, 700)]:
        page = browser.new_page(viewport={"width": width, "height": height})
        errors = []
        page.on("pageerror", lambda error: errors.append(str(error)))
        page.goto(os.environ.get("KWIKPAY_TEST_URL", "http://127.0.0.1:5180/"), wait_until="networkidle")
        calls = []
        page.on("request", lambda request: calls.append(request.url) if request.method == "POST" else None)
        page.get_by_role("button", name="New sale").click()
        page.get_by_role("button", name="See how KwikPay works").click()
        expect(page.get_by_role("heading", name="A customer makes a sale")).to_be_visible()
        page.screenshot(path=str(Path(gettempdir()) / f"kwikpay-example-sale-{width}.png"), full_page=True)
        page.get_by_role("button", name="See the split").click()
        expect(page.get_by_text("R80.00")).to_be_visible()
        expect(page.get_by_text("R20.00")).to_be_visible()
        page.screenshot(path=str(Path(gettempdir()) / f"kwikpay-example-split-{width}.png"), full_page=True)
        page.get_by_role("button", name="See example report").click()
        expect(page.get_by_role("heading", name="The merchant sees the results")).to_be_visible()
        expect(page.get_by_text("Example only.", exact=False)).to_be_visible()
        page.screenshot(path=str(Path(gettempdir()) / f"kwikpay-example-report-{width}.png"), full_page=True)
        assert not calls, calls
        assert page.evaluate("document.documentElement.scrollWidth <= window.innerWidth")
        page.get_by_role("button", name="Finish walkthrough").click()
        page.get_by_role("button", name="Pots & split").click()
        page.get_by_role("button", name="Save pots & split").click()
        expect(page.get_by_role("alert")).to_contain_text("wallet address")
        page.get_by_role("group", name="Pot 1").get_by_role("button", name="Merchant 1").click()
        expect(page.locator("#pot-wallet-0")).to_have_value("https://ilp.interledger-test.dev/kwikpay-merch-1")
        page.get_by_role("group", name="Pot 2").get_by_role("button", name="Merchant 2").click()
        expect(page.locator("#pot-wallet-1")).to_have_value("https://ilp.interledger-test.dev/kwikpay-merch-2")
        page.locator("#pot-wallet-0").fill("https://wallet.example/income")
        page.locator("#pot-wallet-1").fill("https://wallet.example/stock")
        page.get_by_role("button", name="Save pots & split").click()
        expect(page.get_by_role("status")).to_contain_text("saved")
        page.reload(wait_until="networkidle")
        expect(page.locator("#pot-wallet-0")).to_have_value("https://wallet.example/income")
        expect(page.locator("#pot-wallet-1")).to_have_value("https://wallet.example/stock")
        page.get_by_role("button", name="New sale").click()
        page.get_by_role("button", name="Customer wallet").click()
        expect(page.locator("#payer")).to_have_value("https://ilp.interledger-test.dev/wikus-customer")
        page.locator("#sale-total").fill("2.00")
        page.get_by_role("button", name="Preview split").click()
        expect(page.get_by_role("heading", name="R2.00 sale")).to_be_visible()
        expect(page.locator(".legs")).to_contain_text("R1.60")
        expect(page.locator(".legs")).to_contain_text("R0.40")
        expect(page.get_by_role("button", name="Prepare R2.00 Test Wallet payment")).to_be_disabled()
        expect(page.get_by_role("status")).to_contain_text("two Test Wallet destinations")
        page.get_by_role("button", name="Edit sale").click()
        page.locator("#sale-total").fill("100.00")
        page.locator("#payer").fill("https://wallet.example/customer")
        page.get_by_role("button", name="Preview split").click()
        expect(page.get_by_role("heading", name="R100.00 sale")).to_be_visible()
        expect(page.locator(".legs")).to_contain_text("R80.00")
        expect(page.locator(".legs")).to_contain_text("R20.00")
        expect(page.get_by_role("status")).to_contain_text("two Test Wallet destinations")
        if width <= 620:
            wallet = page.get_by_label("Show wallet address for Business income")
            expect(page.locator(".wallet-full").first).to_be_hidden()
            wallet.focus()
            page.keyboard.press("Enter")
            expect(page.locator(".wallet-full").first).to_have_text("https://wallet.example/income")
            expect(page.locator(".wallet-full").first).to_be_visible()
            page.keyboard.press("Enter")
            expect(page.locator(".wallet-full").first).to_be_hidden()
        else:
            expect(page.locator(".wallet-desktop").first).to_contain_text("https://wallet.example/income")
        tools = page.locator(".demo-tools")
        expect(tools.get_by_role("button", name="Simulate split payment")).to_be_hidden()
        tools.locator("summary").focus()
        page.keyboard.press("Enter")
        expect(tools.get_by_role("button", name="Simulate split payment")).to_be_visible()
        tools.get_by_role("button", name="Simulate split payment").click()
        expect(page.get_by_text("SIMULATION ONLY")).to_be_visible()
        expect(page.get_by_role("heading", name="Simulated split complete")).to_be_visible(timeout=5000)
        expect(page.locator(".legs")).to_contain_text("R80.00")
        expect(page.locator(".legs")).to_contain_text("R20.00")
        assert page.locator(".legs").get_by_text("Simulated complete").count() == 2
        assert page.evaluate("sessionStorage.getItem('kwikpay-execution-id')") is None
        page.get_by_role("button", name="Back to sale").click()
        page.get_by_role("button", name="Preview split").click()
        page.locator(".demo-tools summary").click()
        page.get_by_role("button", name="Create tracking record").click()
        expect(page.get_by_role("heading", name="Payment not started")).to_be_visible()
        expect(page.get_by_text("0 / 2")).to_be_visible()
        assert page.locator(".legs").get_by_text("Pending", exact=True).count() == 2
        disclosure = page.get_by_label("Pending Business income: show payment details")
        disclosure.focus()
        page.keyboard.press("Enter")
        expect(page.get_by_text("A tracking record is saved; this payment has not started.").first).to_be_visible()
        page.keyboard.press("Enter")
        expect(page.get_by_text("A tracking record is saved; this payment has not started.").first).to_be_hidden()
        page.emulate_media(reduced_motion="reduce")
        assert page.locator(".pending-sprite i").first.evaluate("el => getComputedStyle(el).animationName") == "none"
        page.emulate_media(reduced_motion="no-preference")
        page.reload(wait_until="networkidle")
        expect(page.get_by_role("heading", name="Payment not started")).to_be_visible()
        execution_id = page.evaluate("sessionStorage.getItem('kwikpay-execution-id')")
        response = page.request.get(f"{os.environ.get('KWIKPAY_TEST_URL', 'http://127.0.0.1:5180/')}api/payment-executions/{execution_id}")
        original = response.json()
        for status, states, title, count in [("PARTIAL", ["COMPLETED", "FAILED"], "Partially completed", "1 / 2"), ("FAILED", ["FAILED", "FAILED"], "Payment failed", "0 / 2"), ("COMPLETED", ["COMPLETED", "COMPLETED"], "Payment complete", "2 / 2")]:
            fixture = {**original, "status": status, "legs": [{"legId": leg["legId"], "status": state} for leg, state in zip(original["legs"], states)]}
            page.route("**/api/payment-executions/*", lambda route: route.fulfill(status=200, content_type="application/json", body=json.dumps(fixture)))
            page.reload(wait_until="networkidle")
            expect(page.get_by_role("heading", name=title)).to_be_visible()
            expect(page.get_by_text(count)).to_be_visible()
            page.unroute_all(behavior="wait")
        page.get_by_role("button", name="Sales", exact=True).click()
        expect(page.get_by_role("heading", name="Sales history", exact=True, level=2)).to_be_visible()
        expect(page.locator(".history-list")).to_contain_text("Tracking only")
        expect(page.locator(".history-list")).to_contain_text("Not started")
        page.locator(".history-item").first.click()
        expect(page.get_by_role("heading", name="Payment not started")).to_be_visible()
        page.get_by_role("button", name="Reports", exact=True).click()
        expect(page.get_by_role("heading", name="Reports", exact=True, level=2)).to_be_visible()
        expect(page.locator(".report-grid")).to_contain_text("Completed test sales")
        expect(page.locator(".report-grid")).to_contain_text("R0.00")
        page.route("**/api/sales-overview?*", lambda route: route.fulfill(status=403, content_type="application/json", body='{}'))
        page.get_by_role("button", name="Refresh").click()
        expect(page.get_by_role("alert")).to_contain_text("do not have access")
        page.unroute_all(behavior="wait")
        page.get_by_role("button", name="Try again").click()
        expect(page.locator(".report-grid")).to_be_visible()
        assert page.evaluate("document.documentElement.scrollWidth <= window.innerWidth")
        assert not errors, errors
        page.screenshot(path=str(Path(gettempdir()) / f"kwikpay-two-pot-{width}.png"), full_page=True)
        page.get_by_role("button", name="Pots & split").click()
        page.get_by_role("group", name="Pot 1").get_by_role("button", name="Merchant 2").click()
        page.get_by_role("group", name="Pot 2").get_by_role("button", name="Merchant 3").click()
        page.locator("#pot-name-0").fill("Takings")
        page.get_by_role("button", name="Save pots & split").click()
        page.locator("#sale-total").fill("3.00")
        page.get_by_role("button", name="Customer wallet").click()
        page.get_by_role("button", name="Preview split").click()
        prepare = page.get_by_role("button", name="Prepare R3.00 Test Wallet payment")
        expect(prepare).to_be_enabled()
        quote_plan = {"amount": {"value": "300"}, "legs": [{"id": "one", "label": "Takings", "amount": {"value": "240"}}, {"id": "two", "label": "Stock reserve", "amount": {"value": "60"}}]}
        page.route("**/api/test-payments/prepare", lambda route: route.fulfill(json={"executionId": "exec_test", "debitMinor": "300"}))
        page.route("**/api/payment-executions/exec_test", lambda route: route.fulfill(json={"executionId": "exec_test", "status": "CREATED", "plan": quote_plan, "legs": []}))
        prepare.click()
        expect(page.get_by_role("heading", name="Review test payment")).to_be_visible()
        expect(page.get_by_text("Takings", exact=True)).to_be_visible()
        page.reload(wait_until="networkidle")
        expect(page.get_by_text("Takings", exact=True)).to_be_visible()
        expect(page.get_by_text("R2.40", exact=True)).to_be_visible()
        expect(page.get_by_role("button", name="Continue to Test Wallet")).to_be_enabled()
        page.close()
    browser.close()
